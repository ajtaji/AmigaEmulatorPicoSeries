"""The README's Controls section, from desktop/controls.pbi - the table the keyboard code and the
Controls tab read - so the three cannot disagree.

    py -3 tools/controls_readme.py          rewrite the section between the markers in README.md
    py -3 tools/controls_readme.py --check  exit 1 if README.md's section is not what the table gives
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / 'desktop' / 'controls.pbi'
README = ROOT / 'README.md'
BEGIN = '<!-- controls: generated by tools/controls_readme.py from desktop/controls.pbi -->'
END = '<!-- controls end -->'

GROUPS = [('Amiga keyboard', ('CTL_KEY', 'CTL_NOTE')),
          ('Mouse (port 1) and joystick (port 2)', ('CTL_MOUSE', 'CTL_JOY', 'CTL_PAD')),
          ('The window', ('CTL_SHORTCUT',))]

# CtlAdd(#KIND, vk, "pc", "amiga"[, code, hidden]) - PureBasic strings have no escapes
ROW = re.compile(r'^\s*CtlAdd\(#(CTL_\w+),\s*[^,]+,\s*"([^"]*)",\s*"([^"]*)"((?:,\s*[^,)]+)*)\)', re.M)


def rows():
    out = []
    for kind, pc, amiga, rest in ROW.findall(TABLE.read_text(encoding='utf-8')):
        args = [a.strip() for a in rest.split(',') if a.strip()]
        if len(args) >= 2 and args[1] not in ('0', ''):
            continue   # hidden: covered by a summary row
        out.append((kind, pc, amiga))
    return out


def md(s):
    return s.replace('\\', '\\\\').replace('|', '\\|').replace('`', '\\`').replace('*', '\\*')


def section():
    r = rows()
    lines = [BEGIN, '']
    for title, kinds in GROUPS:
        lines += ['| ' + title + ' | |', '|---|---|']
        lines += ['| ' + md(pc) + ' | ' + md(amiga) + ' |' for k, pc, amiga in r if k in kinds]
        lines.append('')
    lines.append(END)
    return '\n'.join(lines)


def main():
    text = README.read_text(encoding='utf-8')
    i, j = text.index(BEGIN), text.index(END) + len(END)
    new = text[:i] + section() + text[j:]
    if '--check' in sys.argv:
        if new != text:
            print('README.md: the Controls section differs from desktop/controls.pbi - run tools/controls_readme.py')
            return 1
        print('README.md: the Controls section matches desktop/controls.pbi')
        return 0
    README.write_text(new, encoding='utf-8', newline='\n')
    print('README.md: the Controls section rewritten from desktop/controls.pbi')
    return 0


if __name__ == '__main__':
    sys.exit(main())
